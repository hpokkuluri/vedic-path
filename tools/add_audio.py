#!/usr/bin/env python3
"""Publish voice recordings sent from the app's "Send recordings" button.

Usage:  python3 tools/add_audio.py <folder-or-files...>

Each file is named after the Telugu text it speaks, e.g. u0c05.m4a (= అ) or u0c06-0c35-0c41.m4a (= ఆవు).
Files are copied into audio/ (replacing older takes of the same text) and audio/index.js is rebuilt.
"""
import hashlib, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO = os.path.join(ROOT, 'audio')
NAME = re.compile(r'^(u[0-9a-f]{4}(?:-[0-9a-f]{4})*)\.(m4a|mp4|webm|ogg|mp3|wav)$')

def text_of(key):
    return ''.join(chr(int(h, 16)) for h in key[1:].split('-'))

def main(args):
    os.makedirs(AUDIO, exist_ok=True)
    paths = []
    for a in args:
        paths += [os.path.join(a, f) for f in sorted(os.listdir(a))] if os.path.isdir(a) else [a]
    added = []
    for p in paths:
        m = NAME.match(os.path.basename(p).lower())
        if not m:
            print('skipped (not a recording name):', p); continue
        key = m.group(1)
        for old in os.listdir(AUDIO):                     # replace older takes of the same text
            if old.startswith(key + '.'): os.remove(os.path.join(AUDIO, old))
        shutil.copy(p, os.path.join(AUDIO, os.path.basename(p).lower()))
        added.append(text_of(key))
    entries = []
    for f in sorted(os.listdir(AUDIO)):
        m = NAME.match(f)
        if not m: continue
        v = hashlib.sha1(open(os.path.join(AUDIO, f), 'rb').read()).hexdigest()[:8]
        entries.append(f'  "{m.group(1)}": "audio/{f}?v={v}",   // {text_of(m.group(1))}')
    with open(os.path.join(AUDIO, 'index.js'), 'w', encoding='utf-8') as out:
        out.write('// Published voice recordings for Learn Telugu — generated by tools/add_audio.py, do not edit by hand.\n')
        out.write('window.KIDS_AUDIO = {\n' + '\n'.join(entries) + '\n};\n')
    print(f'added {len(added)}: {" ".join(added)}')
    print(f'audio/index.js now lists {len(entries)} recordings')

if __name__ == '__main__':
    main(sys.argv[1:] or ['.'])
